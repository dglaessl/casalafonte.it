// Builds static language pages (/de/, /it/, /nl/, /da/, /fr/) from index.html + i18n.js,
// so search engines can index every language. Run: node scripts/build_langs.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const window = {}; eval(fs.readFileSync(path.join(root, 'i18n.js'), 'utf8'));
const D = window.CLF_I18N;
const LOCALE = { de: 'de_DE', it: 'it_IT', nl: 'nl_NL', da: 'da_DK', fr: 'fr_FR' };
const esc = s => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const plain = s => s.replace(/<[^>]+>/g, '').replace(/&amp;/g, '&');

function translate(html, T) {
  let out = '', i = 0;
  const re = /<([a-zA-Z0-9]+)\b[^>]*\sdata-i18n="([^"]+)"[^>]*>/g;
  let m, missing = [];
  while ((m = re.exec(html))) {
    const tag = m[1].toLowerCase(), key = m[2], start = m.index + m[0].length;
    // find the matching close tag, counting nested tags of the same name
    const tr = new RegExp('<(/?)' + tag + '\\b[^>]*>', 'gi'); tr.lastIndex = start;
    let depth = 1, t, end = -1;
    while ((t = tr.exec(html))) { depth += t[1] ? -1 : 1; if (!depth) { end = t.index; break; } }
    if (end < 0) throw new Error('No closing tag for ' + key);
    if (T[key] == null) { missing.push(key); continue; }
    out += html.slice(i, start) + T[key]; i = end; re.lastIndex = end;
  }
  return { html: out + html.slice(i), missing };
}

for (const l of Object.keys(D)) {
  const T = D[l];
  let { html, missing } = translate(src, T);
  const url = `https://casalafonte.it/${l}/`;
  html = html
    .replace('<html lang="en">', `<html lang="${l}">`)
    .replace(/<title>[^<]*<\/title>/, `<title>${esc(plain(T.meta_t))}</title>`)
    .replace(/<meta name="description" content="[^"]*">/, `<meta name="description" content="${esc(T.meta_d)}">`)
    .replace(/<meta property="og:title" content="[^"]*">/, `<meta property="og:title" content="${esc(plain(T.meta_t))}">`)
    .replace(/<meta property="og:description" content="[^"]*">/, `<meta property="og:description" content="${esc(T.meta_d)}">`)
    .replace(/<meta property="og:locale" content="[^"]*">/, `<meta property="og:locale" content="${LOCALE[l]}">`)
    .replace(/<meta property="og:url" content="[^"]*">/, `<meta property="og:url" content="${url}">`)
    .replace(/<link rel="canonical" href="[^"]*">/, `<link rel="canonical" href="${url}">`)
    .replace('<link rel="canonical"', `<script>window.CLF_PAGE_LANG="${l}";</script>\n<link rel="canonical"`)
    .replace(/(<button type="button" id="l-[a-z]+" data-l="[a-z]+")>/g, '$1>');
  fs.mkdirSync(path.join(root, l), { recursive: true });
  fs.writeFileSync(path.join(root, l, 'index.html'), '<!-- Generated by scripts/build_langs.js from index.html and i18n.js. Do not edit. -->\n' + html);
  console.log(l, 'written', missing.length ? 'missing: ' + missing.join(',') : '');
}

const langs = ['en', ...Object.keys(D)], loc = l => `https://casalafonte.it/${l === 'en' ? '' : l + '/'}`;
const today = new Date().toISOString().slice(0, 10);
const sm = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${langs.map(l => `  <url>
    <loc>${loc(l)}</loc>
    <lastmod>${today}</lastmod>
${langs.map(k => `    <xhtml:link rel="alternate" hreflang="${k}" href="${loc(k)}"/>`).join('\n')}
    <xhtml:link rel="alternate" hreflang="x-default" href="${loc('en')}"/>
  </url>`).join('\n')}
</urlset>
`;
const prev = fs.existsSync(path.join(root, 'sitemap.xml')) ? fs.readFileSync(path.join(root, 'sitemap.xml'), 'utf8') : '';
if (prev.replace(/<lastmod>[^<]*<\/lastmod>/g, '') !== sm.replace(/<lastmod>[^<]*<\/lastmod>/g, '') || !prev) fs.writeFileSync(path.join(root, 'sitemap.xml'), sm);
